"""Playbook knowledge base.

The agent never writes official playbooks in Playbooks/; analysts can edit them
from the UI, and every save first copies the previous version to
playbook_history/. Human-approved AI drafts live in playbook_proposals/ and are
loaded next to the official ones, clearly labelled. Who owns each step (agent vs.
human) comes from config/playbook_steps.yaml, matched against the playbook text.
"""

import hashlib
import json
import re
from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path

import yaml

from . import config
from .models import Playbook, StepRule

L1_PHASES = ("Detection", "Analysis", "Containment")


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def parse_playbook(path: Path, origin: str = "official") -> Playbook:
    text = path.read_text()
    title = re.search(r"^# (?:Playbook: )?(.+)$", text, re.M)
    trigger = re.search(r"^Trigger: alert_type = (.+)$", text, re.M)
    attack = re.search(r"^ATT&CK mapping: (.+?)(?:\n\n|$)", text, re.M | re.S)
    sections = {
        m.group(1).strip(): normalize(m.group(2))
        for m in re.finditer(r"^## (.+?)\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    }
    return Playbook(
        slug=path.stem,
        path=config.rel(path),
        title=title.group(1).strip() if title else path.stem,
        alert_type=trigger.group(1).strip() if trigger else path.stem.replace("_", " ").title(),
        attack_mapping=normalize(attack.group(1)) if attack else "",
        sections=sections,
        text=text,
        origin=origin,
    )


def load_playbooks() -> dict[str, Playbook]:
    """Official playbooks plus any human-approved drafts, keyed by slug."""
    books = {p.stem: parse_playbook(p) for p in sorted(config.PLAYBOOK_DIR.glob("*.md"))}
    approved = config.PROPOSALS_DIR / "approved"
    if approved.exists():
        for p in sorted(approved.glob("*.md")):
            books[f"approved/{p.stem}"] = parse_playbook(p, origin="ai_drafted_human_approved")
    return books


def playbooks_by_type() -> dict[str, Playbook]:
    """alert_type -> official playbook (approved new-type drafts fill gaps only)."""
    out: dict[str, Playbook] = {}
    for book in load_playbooks().values():
        if book.origin == "official" or book.alert_type not in out:
            out.setdefault(book.alert_type, book)
    return out


@lru_cache(maxsize=1)
def load_step_rules() -> tuple[StepRule, ...]:
    raw = yaml.safe_load(config.PLAYBOOK_STEPS.read_text()) or {}
    return tuple(
        StepRule(playbook=slug, **rule) for slug, rules in raw.items() for rule in rules or []
    )


def validate_step_rules() -> list[str]:
    """Every rule must quote text that still exists in its playbook.

    Returns the problems found; an empty list means the overlay is in sync.
    """
    books = load_playbooks()
    problems = []
    for rule in load_step_rules():
        book = books.get(rule.playbook)
        if book is None:
            problems.append(f"{rule.playbook}: playbook not found")
        elif normalize(rule.match) not in normalize(book.text):
            problems.append(f"{rule.playbook}: quoted text no longer present: {rule.match!r}")
    return problems


def rules_for(slug: str) -> list[StepRule]:
    return [r for r in load_step_rules() if r.playbook == slug]


def build_index(books: dict[str, Playbook] | None = None) -> str:
    """Markdown index of every playbook: what triggers it and what it maps to."""
    books = books or load_playbooks()
    lines = [
        "# Playbook Index",
        "",
        "Generated by `python -m soc_agent.index` from `Playbooks/`. Do not edit by hand.",
        "",
        "| Playbook | Trigger (alert_type) | ATT&CK | Origin |",
        "|---|---|---|---|",
    ]
    for slug, book in books.items():
        techniques = ", ".join(dict.fromkeys(re.findall(r"T\d{4}(?:\.\d{3})?", book.attack_mapping)))
        lines.append(f"| `{slug}` | {book.alert_type} | {techniques or '-'} | {book.origin} |")
    lines += ["", "## Human-owned steps", ""]
    for rule in load_step_rules():
        lines.append(f"- `{rule.playbook}` ({rule.owner}, gate={rule.gate}): \"{rule.match}\"")
    return "\n".join(lines) + "\n"


# ---- Editing from the UI ----


class PlaybookConflict(Exception):
    """The file changed since the editor loaded it."""


def playbook_file(slug: str) -> Path:
    """Disk path for a known playbook slug (unknown slugs raise KeyError)."""
    if slug not in load_playbooks():
        raise KeyError(slug)
    if slug.startswith("approved/"):
        return config.PROPOSALS_DIR / "approved" / f"{slug.split('/', 1)[1]}.md"
    return config.PLAYBOOK_DIR / f"{slug}.md"


def content_hash(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:16]


def _history_dir(slug: str) -> Path:
    return config.PLAYBOOK_HISTORY / slug.replace("/", "__")


def history(slug: str) -> list[dict]:
    log = _history_dir(slug) / "history.jsonl"
    if not log.exists():
        return []
    return [json.loads(line) for line in reversed(log.read_text().splitlines()) if line.strip()]


def save_playbook(slug: str, text: str, editor: str, base_hash: str, note: str = "") -> dict:
    """Overwrite a playbook after backing up the current version.

    Rejects the save if the file changed since `base_hash` was read, or if the
    Trigger line is gone (the pipeline maps alert types to playbooks by it).
    Returns warnings for anything the save broke but did not block.
    """
    path = playbook_file(slug)
    current = path.read_text()
    if content_hash(current) != base_hash:
        raise PlaybookConflict(slug)
    if not re.search(r"^Trigger: alert_type = .+$", text, re.M):
        raise ValueError("The playbook must keep its 'Trigger: alert_type = ...' line.")
    text = text.rstrip() + "\n"
    if text == current:
        return {"saved": False, "warnings": [], "hash": base_hash}

    stamp = datetime.now(timezone.utc)
    backup_dir = _history_dir(slug)
    backup_dir.mkdir(parents=True, exist_ok=True)
    backup = backup_dir / f"{stamp:%Y%m%dT%H%M%S%fZ}.md"
    backup.write_text(current)
    with open(backup_dir / "history.jsonl", "a") as log:
        log.write(json.dumps({
            "saved_at": stamp.isoformat(), "editor": editor, "note": note,
            "previous_version": config.rel(backup),
        }) + "\n")
    path.write_text(text)

    book = parse_playbook(path)
    warnings = [f"Missing section: {phase}" for phase in L1_PHASES if phase not in book.sections]
    warnings += [p for p in validate_step_rules() if p.startswith(f"{slug}:")]
    return {"saved": True, "warnings": warnings, "hash": content_hash(text), "backup": config.rel(backup)}
